"""P39 phase 1 - the "lane-0 pre-pose" audit, offline and static.

The lever as briefed is "apply the two-line's solved *left* pre-pose (the
two-line station y=0.00's station-specific pre-pose) to the single-arm lane-0".
This script reads the source and asks whether that artifact exists.

Answer: **it does not.**  `_prepare_two_line_stations` solves a station-specific
pre-pose only for an arm whose station is *off* the calibrated pick point, and
the two-line's left station is the calibrated pick point (y = +0.00), so the
left is skipped and runs the shared `grasp` config - the same config the
single-arm line runs.  Its catch aim is also identical (`station_y_for(left)`
+ `_two_line_catch_lead()`, and the lead's shipped default is 0.0).  So there is
nothing to port, and the two-line left's 0/10 cnp cannot license a pre-pose
port: the two-line left differs from the single-arm left by the *supply* (the
dense sheet + the balanced mix), the *scheduler* (concurrent right arm, shared
tick) and the adopted two-line carry monitor - not by a pose.

    python3 logs/p39/prepose_audit.py            # the table + the code facts
    python3 logs/p39/prepose_audit.py --assert   # + the pins
"""

from __future__ import annotations

import re
import sys

TASKS = "src/fruit_sorting/tasks.py"
ASSETS = "src/fruit_sorting/assets.py"


def read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def facts() -> list[tuple[str, str, bool]]:
    """(name, the extracted source fact, the pin it must satisfy)."""
    tasks = read(TASKS)
    assets = read(ASSETS)
    out: list[tuple[str, str, bool]] = []

    m = re.search(r'left_y = float\(os\.environ\.get\("FRUIT_BIARM_STATION_L", "([-\d.]+)"\)\)', tasks)
    out.append(("the two-line left station default", m.group(1) if m else "<missing>",
                bool(m) and m.group(1) == "0.0"))
    m = re.search(r'right_y = float\(os\.environ\.get\("FRUIT_BIARM_STATION_R", "([-\d.]+)"\)\)', tasks)
    out.append(("the two-line right station default", m.group(1) if m else "<missing>",
                bool(m) and m.group(1) == "-0.10"))
    m = re.search(r'pick_y: float = ([\d.]+)', assets)
    out.append(("the calibrated pick point (cfg.pick_y)", m.group(1) if m else "<missing>",
                bool(m) and m.group(1) == "0.0"))
    # the skip predicate inside `_prepare_two_line_stations`
    body = tasks[tasks.index("def _prepare_two_line_stations"):]
    body = body[: body.index("def _two_line_prepose_locked")]
    m = re.search(r"if abs\(target_y - float\(self\.cfg\.pick_y\)\) < 1e-9:\n\s+continue", body)
    out.append(("the station-specific solve is skipped at the calibrated pick point",
                "skip present" if m else "<missing>", bool(m)))
    # the shipped catch lead
    m = re.search(r'FRUIT_BIARM_CATCH_LEAD_L", "([-\d.]+)"', tasks)
    out.append(("the two-line left catch-lead default",
                m.group(1) if m else "<missing>", bool(m) and m.group(1) == "0.0"))
    # the non-two-line short circuit
    m = re.search(r"if session is None or not getattr\(session, \"twoline\", False\):\n\s+return 0\.0",
                  tasks)
    out.append(("the catch lead is 0.0 off the two-line", "present" if m else "<missing>", bool(m)))
    # the aim
    m = re.search(
        r"self\.station_y_for\(self\.current_arm\) \+ self\._two_line_catch_lead\(\)", tasks)
    out.append(("the aim = station_y + the two-line lead", "present" if m else "<missing>",
                bool(m)))
    # the pre-pose fallback
    m = re.search(r'target = self\._pose\(name, "grasp"\) if prepose is None else prepose', tasks)
    out.append(("a None pre-pose falls back to the calibrated `grasp` config",
                "present" if m else "<missing>", bool(m)))
    # the documented left place posture (the posture correlate)
    m = re.search(r"swings the tool to (\d+(?:\.\d+)?) deg\s+from", tasks)
    out.append(("the documented left place posture (deg from vertical)",
                m.group(1) if m else "<missing>", bool(m) and float(m.group(1)) > 90.0))
    # the unmeasured-by-record wrist hold
    m = re.search(r'hold_wrist = os\.environ\.get\("FRUIT_CARRY_HOLD_QUAT", "0"\) == "1"', tasks)
    out.append(("`FRUIT_CARRY_HOLD_QUAT` exists, default off", "present" if m else "<missing>",
                bool(m)))
    m = re.search(r"the IK stalls ~12 cm short of the output line", tasks)
    out.append(("the hold-all-legs form is documented as measured negative (`logs/444`)",
                "present" if m else "<missing>", bool(m)))
    return out


def main() -> int:
    print("# P39 phase-1 lane-0 pre-pose audit (generated by logs/p39/prepose_audit.py)\n")
    print("## 1. The code facts\n")
    print("| # | fact | value | pin |")
    print("|---|---|---|---|")
    rows = facts()
    for i, (name, value, ok) in enumerate(rows, 1):
        print(f"| {i} | {name} | `{value}` | {'PASS' if ok else 'FAIL'} |")
    print()

    print("## 2. What the two-line left and the single-arm left actually share\n")
    print("| term | two-line left | single-arm left | same? |")
    print("|---|---|---|---|")
    for term, tl, sl, same in (
        ("pick station y", "+0.00 (default)", "cfg.pick_y = +0.00", "**yes**"),
        ("station-specific pre-pose", "none - the solve is skipped at the pick point",
         "none", "**yes**"),
        ("pre-pose fallback", "the calibrated `grasp` config", "the calibrated `grasp` config",
         "**yes**"),
        ("catch aim", "station_y + lead(0.0)", "station_y", "**yes**"),
        ("hand", "OpenArm, same four finger links", "same", "**yes**"),
        ("supply", "dense wave sheet, balanced A:B:C 0.375/0.375/0.25",
         "scattered 16-fruit pool, A:B:C 0.5/0.3/0.2", "no"),
        ("concurrency", "concurrent right arm, one shared physics tick per round",
         "single arm", "no"),
        ("carry monitor", "`FRUIT_CARRY_MONITOR` adopted (P10-C.3, `CONFIRM_MM=8`)",
         "never armed (`_carry_monitor_active` needs direct_capture or two-line)", "no"),
        ("grade routing", "pure: left takes grade A only", "lane 0 = grade A", "**yes**"),
    ):
        print(f"| {term} | {tl} | {sl} | {same} |")
    print()

    print("## 3. What the audit leaves\n")
    print(
        "* The briefed artifact (\"the two-line's solved left pre-pose\") does **not "
        "exist**: the solve skips the arm whose station is the calibrated pick point, "
        "and the two-line's left station *is* the calibrated pick point."
    )
    print(
        "* Therefore the two-line left's 0/10 cnp is **not** a pose result, and the "
        "single-arm left has no pose difference to inherit.  The only remaining pose "
        "term on the P33 section 2.4 correlate (the 93.6 deg place solve) is the "
        "**wrist attitude**, which is `FRUIT_CARRY_HOLD_QUAT` - built, default off, and "
        "measured negative *when it is held through the place leg* (`logs/444`: the IK "
        "stalls ~12 cm short of the output line).  Holding it through the **lift** leg "
        "only is the unmeasured, bounded form."
    )
    print(
        "* The honest lever-2 re-specification is therefore either (a) the lift-only "
        "wrist hold, or (b) an explicitly *authored* left pre-pose (a different IK seed "
        "or attitude at the shared station) - which is a new design, not a port, and "
        "needs its own offline evidence that it changes the close geometry."
    )
    print()

    if "--assert" in sys.argv:
        print("## `--assert`\n")
        bad = sum(0 if ok else 1 for _n, _v, ok in rows)
        for name, value, ok in rows:
            print(f"- {'PASS' if ok else 'FAIL'} {name} (got `{value}`)")
        print(f"\n{'PASS' if bad == 0 else f'{bad} FAILED'}")
        return 1 if bad else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
