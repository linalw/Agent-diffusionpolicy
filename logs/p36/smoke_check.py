"""P36 phase 1: the per-cell observation smoke's check (offline; reads the logs).

    python3 logs/p36/smoke_check.py            # -> logs/p36/P1_smoke.txt

Reads the six one-episode runs `logs/p36/run_smoke.sh` wrote and asserts the
manipulation check the 2x2 depends on (PREREG section 3), from the log text
alone:

* **S1** the proprio substitution: the spoofed values are the file's vector; the
  *no-op* cells (`s1b` spoof=ready on the ready arm, `s2b` spoof=back on the
  parked arm) report `drift = max|live - written| <= 0.02` rad, which is the
  statement that the vector reproduces the physical cell's proprio;
* **S2** `rest_same=1` in every cell - the md5 of the 25-D proprio with the 7
  spoofed indices zeroed is equal before/after, i.e. nothing else moved;
* **S3** the `[park]` M1 read: the arm holds the pose the cell names;
* **S4** the image cell: the inactive arm has pixels in the target's disc bbox
  in the *ready* cells and none in the *parked* cells - the image follows the
  arm, not the spoof;
* the **cross-cell hash identity**: cell 3's pre-spoof proprio hash equals cell
  2's (both parked) and cell 4's equals cell 1's (both ready) - the physical
  first call is bit-identical inside each pair.
"""

from __future__ import annotations

import json
import os
import re
import sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SMOKE = os.path.join(REPO, "logs", "p36", "smoke")
OUT = os.path.join(REPO, "logs", "p36", "P1_smoke.txt")

SPOOF = re.compile(
    r"\[spoof\] episode (\d+) pose=(\S+) applied=(\d+) side=(\S+) idx=(\S+) "
    r"live=(\S+) obs=(\S+) pre_md5=(\w+) obs_md5=(\w+) rest_md5=(\w+) "
    r"rest_same=(\d) calls=(\d+) drift=(\S+)"
)
PARK = re.compile(
    r"\[park\] episode (\d+) arm=(\w+) inactive=(\w+) park=(\w+) "
    r"m1_hold=([-+]?[\d.]+) m1_hold_ok=(\d) m1_cmd=([-+]?[\d.]+) "
    r"m2_arm=([-+]?[\d.]+) m2_arm_ok=(-?\d) .*?arm_px=(\d+)"
)
RL = re.compile(r"\[rl\] episode (\d+): (\w+) d=([\d.]+)cm bin=(-?\d+) arm=(\w+) "
                r"success=(\w+) grasped=(\w+) placed=(\w+) ticks=(\d+)")

#: label -> (the cell, the pose the obs must carry, whether the arm is parked)
CELLS = {
    "s1": ("1 ready/ready", None, False),
    "s2": ("2 park/park", None, True),
    "s3": ("3 park-image/ready-proprio", "ready", True),
    "s4": ("4 ready-image/park-proprio", "back", False),
    "s1b": ("1b ready/ready (written)", "ready", False),
    "s2b": ("2b park/park (written)", "back", True),
}

failures: list[str] = []
lines: list[str] = []


def put(text: str = "") -> None:
    lines.append(text)


def check(name: str, ok: bool, detail: str = "") -> None:
    lines.append(f"  {'PASS' if ok else 'FAIL'}  {name}" + (f"  [{detail}]" if detail else ""))
    if not ok:
        failures.append(name)


def load(label: str) -> dict:
    path = os.path.join(SMOKE, f"{label}.log")
    text = open(path, encoding="utf-8", errors="ignore").read()
    spoof = SPOOF.search(text)
    park = PARK.search(text)
    rl = RL.search(text)
    if not (spoof and park and rl):
        raise SystemExit(f"{path}: missing a [spoof]/[park]/[rl] row")
    return {
        "spoof": {
            "pose": spoof.group(2), "applied": int(spoof.group(3)),
            "side": spoof.group(4), "idx": spoof.group(5),
            "pre_md5": spoof.group(8), "obs_md5": spoof.group(9),
            "rest_same": int(spoof.group(11)), "drift": spoof.group(13),
        },
        "park": {
            "arm": park.group(2), "inactive": park.group(3), "park": park.group(4),
            "m1_hold": float(park.group(5)), "m1_ok": int(park.group(6)),
            "arm_px": int(park.group(10)),
        },
        "rl": {
            "arm": rl.group(5), "success": rl.group(6), "grasped": rl.group(7),
            "placed": rl.group(8), "ticks": int(rl.group(9)),
        },
    }


def main() -> int:
    poses = json.load(open(os.path.join(REPO, "configs", "proprio_spoof.json"),
                           encoding="utf-8"))["poses"]
    put("P36 phase 1 - the per-cell observation smoke (1 episode, seed 77)")
    put("=" * 78)
    put("generated by logs/p36/smoke_check.py from logs/p36/smoke/*.log")
    put("")
    put(f"    {'cell':32s} {'arm':5s} {'outcome':10s} {'spoof':6s} {'drift':8s} "
        f"{'park':6s} {'arm_px':6s} pre_md5 / obs_md5")
    runs = {}
    for label, (name, want_pose, parked) in CELLS.items():
        runs[label] = data = load(label)
        s, p, r = data["spoof"], data["park"], data["rl"]
        outcome = "ok" if r["success"] == "True" else (
            "carried" if r["grasped"] == "True" else "no-grasp")
        put(f"    {name:32s} {r['arm']:5s} {outcome:10s} "
            f"{s['pose']:6s} {s['drift']:8s} {p['park']:6s} {p['arm_px']:<6d} "
            f"{s['pre_md5'][:8]} / {s['obs_md5'][:8]}")
    put("")

    put("[S1] the proprio substitution (the 7 indices, the vector, the no-op drift)")
    put("")
    for label, (name, want_pose, _) in CELLS.items():
        s = runs[label]["spoof"]
        if want_pose is None:
            check(f"{label}: no spoof requested -> applied=0",
                  s["applied"] == 0 and s["pre_md5"] == s["obs_md5"], f"applied={s['applied']}")
            continue
        check(f"{label}: applied=1, the 7 left-arm indices",
              s["applied"] == 1 and s["idx"] == "0,2,4,6,8,10,12", s["idx"])
    for label in ("s3", "s4"):
        s = runs[label]["spoof"]
        want = ",".join(f"{v:+.3f}" for v in poses[CELLS[label][1]]["left"])
        # The row prints the *written* values in the obs field; parse the log text
        # for the obs vector (the regex keeps only the hashes).
        text = open(os.path.join(SMOKE, f"{label}.log"), encoding="utf-8").read()
        found = re.search(r"\[spoof\].* obs=(\S+)", text)
        check(f"{label}: the written values are the '{CELLS[label][1]}' vector",
              found is not None and found.group(1) == want,
              found.group(1) if found else "-")
    for label in ("s1b", "s2b"):
        drift = float(runs[label]["spoof"]["drift"])
        check(f"{label}: the no-op drift <= 0.02 rad (the source vector)",
              drift <= 0.02, f"{drift:.4f} rad")
    for label in ("s3", "s4"):
        drift = float(runs[label]["spoof"]["drift"])
        check(f"{label}: the live arm is NOT at the written pose (the substitution bites)",
              drift > 0.30, f"{drift:.4f} rad")
    put("")

    put("[S2] the rest of the observation (rest_same) and the untouched channels")
    put("")
    for label in CELLS:
        check(f"{label}: rest_same=1", runs[label]["spoof"]["rest_same"] == 1)
    put("    (the [spoof] row's rest_md5 is the md5 of the 25-D proprio with the 7")
    put("     indices zeroed, before and after: equal means only those 7 changed)")
    put("")

    put("[S3] the arm holds the cell's pose ([park] M1, vs the achieved pose)")
    put("")
    for label, (name, _, parked) in CELLS.items():
        p = runs[label]["park"]
        want = "back" if parked else "ready"
        check(f"{label}: park={want}, M1 held", p["park"] == want and p["m1_ok"] == 1,
              f"park={p['park']} m1_hold={p['m1_hold']:+.3f}")
    put("")

    put("[S4] the image cell follows the arm, not the spoof ([park] band census)")
    put("")
    for label, (name, _, parked) in CELLS.items():
        p = runs[label]["park"]
        if parked:
            check(f"{label}: no inactive-arm pixels in the disc bbox",
                  p["arm_px"] == 0, f"arm_px={p['arm_px']}")
        else:
            check(f"{label}: the inactive arm is in the disc bbox",
                  p["arm_px"] > 0, f"arm_px={p['arm_px']}")
    put("")

    put("[5] the cross-cell hash identity (the physical first call)")
    put("")
    check("s3's pre-spoof proprio hash == s2's (both parked)",
          runs["s3"]["spoof"]["pre_md5"] == runs["s2"]["spoof"]["obs_md5"],
          f"{runs['s3']['spoof']['pre_md5'][:8]}")
    check("s4's pre-spoof proprio hash == s1's (both ready)",
          runs["s4"]["spoof"]["pre_md5"] == runs["s1"]["spoof"]["obs_md5"],
          f"{runs['s4']['spoof']['pre_md5'][:8]}")
    check("the two parked cells share one pre hash",
          runs["s2"]["spoof"]["pre_md5"] == runs["s3"]["spoof"]["pre_md5"])
    check("the two ready cells share one pre hash",
          runs["s1"]["spoof"]["obs_md5"] == runs["s4"]["spoof"]["pre_md5"])
    put("")

    put("[6] THE OUTCOME (a smoke: one episode per cell, no claim)")
    put("")
    put("    The four cells present the same fruit (apple 6.8 cm, right arm) - the")
    put("    first call's state is identical inside each pair - and the six single")
    put("    episodes already diverge: s1 carried, s2 ok, s3 ok, s4 no-grasp,")
    put("    s1b no-grasp (its input differs from s1 by <= 0.006 rad in 7 joints),")
    put("    s2b ok. One episode per cell is a smoke, not a rate; the 2x2 is the")
    put("    batch (PREREG section 6).")
    put("")

    put("[7] VERDICT")
    put("")
    put(f"    failures={len(failures)}")
    if failures:
        put(f"    failed: {failures}")
    text = "\n".join(lines) + "\n"
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(text, end="")
    print(f"\nwrote {os.path.relpath(OUT, REPO)}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
