#!/usr/bin/env python3
"""P40 G0 - the `[effort]` lines of the two claimed runs, as one table.

Read-only: parses `logs/p40/p2/effort_sub1.log` and `effort_sub4.log` (the
shipped substeps and `FRUIT_SUBSTEPS=4`) and prints, per row, the tactile
per-face/sum, the two finger joints' projected joint force (`proj`), the drive
law (`kpc`) and the target error (`err`), so the tactile can be graded against
a physics instrument taken on the same tick.

    python3 logs/p40/p2/effort_table.py > logs/p40/p2/effort_table.txt
"""

from __future__ import annotations

import re
import sys

ROWS = (
    ("sub1", "logs/p40/p2/effort_sub1.log"),
    ("sub4", "logs/p40/p2/effort_sub4.log"),
)

HEAD = re.compile(
    r"\[effort\] (?P<arm>\w+) idx=(?P<idx>-?\d+) (?P<label>\S+) sub=(?P<sub>\d+) "
    r"t=(?P<t>[\d.]+)s n=(?P<n>\d+) \| "
    r"tact\[N\]=(?P<f0>[-\d.]+),(?P<f1>[-\d.]+) sum=(?P<sum>[-\d.]+) "
    r"contacts=(?P<contacts>\d+) \| "
    r"(?P<j1>[^:]+): eff\[N\]=(?P<j1eff>\S+) proj\[N\]=(?P<j1proj>\S+) "
    r"kpc\[N\]=(?P<j1kpc>\S+) Fsat\[N\]=(?P<j1fsat>\S+) q\[mm\]=(?P<j1q>\S+) "
    r"tgt\[mm\]=(?P<j1tgt>\S+) err\[mm\]=(?P<j1err>\S+) \| "
    r"(?P<j2>[^:]+): eff\[N\]=(?P<j2eff>\S+) proj\[N\]=(?P<j2proj>\S+) "
    r"kpc\[N\]=(?P<j2kpc>\S+) Fsat\[N\]=(?P<j2fsat>\S+) q\[mm\]=(?P<j2q>\S+) "
    r"tgt\[mm\]=(?P<j2tgt>\S+) err\[mm\]=(?P<j2err>\S+)"
)


def main() -> int:
    rows = []
    for tag, path in ROWS:
        with open(path) as handle:
            for line in handle:
                match = HEAD.search(line)
                if match is None:
                    continue
                d = match.groupdict()
                rows.append((tag, d))

    print("P40 G0 - the finger drive vs the tactile, per event (5-tick medians)")
    print("generated by logs/p40/p2/effort_table.py")
    print()
    print(
        "run  arm   idx  event                 tact_face0 tact_face1  tact_sum  "
        "j1proj  j2proj  proj_sum  j1err_mm  j1kpc_N   contacts"
    )
    print("-" * 118)
    for tag, d in rows:
        f0 = float(d["f0"])
        f1 = float(d["f1"])
        s = float(d["sum"])
        p1 = None if d["j1proj"] == "n/a" else float(d["j1proj"])
        p2 = None if d["j2proj"] == "n/a" else float(d["j2proj"])
        psum = "n/a" if p1 is None or p2 is None else f"{p1 + p2:+.2f}"
        print(
            f"{tag:4s} {d['arm']:5s} {d['idx']:>4s}  {d['label']:<21s} "
            f"{f0:10.2f} {f1:10.2f} {s:9.2f}  "
            f"{(p1 if p1 is not None else float('nan')):+7.2f}  "
            f"{(p2 if p2 is not None else float('nan')):+7.2f}  {psum:>8s}  "
            f"{float(d['j1err']):+8.2f}  {float(d['j1kpc']):+9.2f}  {d['contacts']:>8s}"
        )

    # The two ratios the read quotes: tactile per face vs the joint it rides, and
    # the load-vs-cap fraction, contact rows only.
    print()
    print("contact rows only (tact_sum > 1 N): tactile vs the same-tick physics reaction")
    print(
        "run   n   tact_sum_med  proj_sum_med  tact/proj   |j1proj|_med  load/cap_j1  "
        "|err|_med_mm  k_eff_N/m  k_authored*err_N"
    )
    print("-" * 118)
    for tag in ("sub1", "sub4"):
        sel = [
            d
            for t, d in rows
            if t == tag
            and float(d["sum"]) > 1.0
            and d["j1proj"] != "n/a"
        ]
        if not sel:
            continue
        sums = sorted(float(d["sum"]) for d in sel)
        projs = sorted(float(d["j1proj"]) + float(d["j2proj"]) for d in sel)
        j1 = sorted(abs(float(d["j1proj"])) for d in sel)
        caps = sorted(abs(float(d["j1fsat"])) for d in sel)
        errs = sorted(abs(float(d["j1err"])) for d in sel)
        med = lambda v: 0.5 * (v[len(v) // 2 - 1] + v[len(v) // 2]) if len(v) % 2 == 0 else v[len(v) // 2]  # noqa: E731
        ratio = med(sums) / med(projs) if med(projs) else float("nan")
        k_eff = med(j1) / (med(errs) * 1e-3) if med(errs) else float("inf")
        k_auth = 1.0e6 * med(errs) * 1e-3
        print(
            f"{tag:5s} {len(sel):2d}  {med(sums):11.2f}  {med(projs):12.2f}  "
            f"{ratio:9.3f}  {med(j1):10.2f}  {med(j1) / med(caps):11.3f}  "
            f"{med(errs):10.2f}  {k_eff:9.0f}  {k_auth:15.0f}"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
