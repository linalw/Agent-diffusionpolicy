#!/usr/bin/env python3
"""P41 phase 1 - the damping-ratio collapse, re-derived from every sweep log.

The 8-cell grid varies `FRUIT_FINGER_STIFFNESS` with `control.py`'s own default
damping (2 % of k), so it cannot tell a stiffness effect from a damping one. The
brackets separate them, and what the corpus collapses on is the drive's
**damping ratio c/k** - not k, and not c alone:

  * `rho_asset` (k = 1e6, c = 100 - the asset's authored gains, authored on both
    joints) is **byte-identical to the shipped cell** and reads 4.52/4.23 N;
  * `rho_soft` (k = 3e5, c = 100) also stays at the shipped level (4.44 N);
  * at a **fixed c = 1000**, k = 1e5 / 3e5 / 1e6 reads 9.81 / 10.00 / 4.49 N.

This script prints every cell of that corpus as (k, c, c/k) -> force, so the
collapse (and its threshold) is checked against the logs, not asserted.

    python3 logs/p41/ratio_collapse.py > logs/p41/ratio_collapse.txt
"""

from __future__ import annotations

import re
import statistics as st
from pathlib import Path

ROOTS = (
    Path("logs/p41/sweep"),
    Path("logs/p41/sweep_bracket"),
    Path("logs/p41"),
)

BANNER = re.compile(
    r"\[effort\] FRUIT_GRIP_EFFORT=1 reporting only.*?k=([\d.]+)/([\d.]+)N/m "
    r"c=([\d.]+)/([\d.]+)Ns/m maxForce=([\d.]+)/([\d.]+)N"
)
EFFORT = re.compile(r"\[effort\] \w+ idx=-?\d+ close_freeze .*? sum=([-\d.]+) ")
SUB = re.compile(r"sub=(\d+)")


def main() -> int:
    seen: dict[Path, tuple] = {}
    for root in ROOTS:
        for path in sorted(root.glob("*.log")):
            seen.setdefault(path.resolve(), (root, path))
    rows = []
    for _root, path in seen.values():
        text = path.read_text(errors="replace")
        b = BANNER.search(text)
        if b is None:
            continue
        k1, k2, c1, c2, cap1, cap2 = (float(x) for x in b.groups())
        sub = SUB.search(text)
        sums = [float(m.group(1)) for m in EFFORT.finditer(text)]
        if not sums:
            continue
        rows.append(
            {
                "name": path.stem,
                "sub": int(sub.group(1)) if sub else 1,
                "k": k1,
                "c": c1,
                "ratio": c1 / k1 if k1 else float("nan"),
                "f": float(st.median(sums)),
                "n": len(sums),
                "spread": (min(sums), max(sums)),
                "cap": cap1,
            }
        )

    rows.sort(key=lambda r: (r["sub"], r["ratio"], r["k"]))
    print("P41 phase 1 - does the delivered pinch collapse on the drive's damping ratio?")
    print("generated by logs/p41/ratio_collapse.py; every close_freeze row of the corpus")
    print()
    print("The ratio c/k is read from the [effort] banner (the runtime gain read-back),")
    print("force is the median of that cell's close_freeze tactile sums (n grabs).")
    print()
    print(
        "cell            sub  k1[N/m]   c1[Ns/m]   c/k      force[N]  n  [min,max]"
    )
    print("-" * 84)
    for r in rows:
        print(
            f"{r['name']:15s} {r['sub']:>3d} {r['k']:9.0f} {r['c']:10.0f} "
            f"{r['ratio']:8.5f} {r['f']:9.2f} {r['n']:2d}  "
            f"[{r['spread'][0]:.2f},{r['spread'][1]:.2f}]"
        )

    print()
    print("binned by c/k (all substeps pooled):")
    print("-" * 84)
    for lo, hi in ((0.0, 5e-4), (5e-4, 0.001), (0.001, 0.003), (0.003, 0.011),
                   (0.011, 0.05)):
        sel = [r["f"] for r in rows if lo <= r["ratio"] < hi]
        if not sel:
            continue
        print(
            f"  c/k in [{lo:.4f}, {hi:.4f}): n_cells={len(sel):2d} "
            f"force_med={float(st.median(sel)):5.2f} N  "
            f"range=[{min(sel):.2f},{max(sel):.2f}]"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
